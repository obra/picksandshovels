export const GLYPH_H = 7;

export function glyph(ch) {
  return G[ch] || G[ch.toUpperCase()] || G['?'];
}

export function textWidth(text) {
  let w = 0;
  for (const ch of text) w += glyph(ch)[0].length + 1;
  return Math.max(0, w - 1);
}

// Calls plot(x, y) for every inked pixel of text, origin top-left.
export function rasterize(text, plot) {
  let x0 = 0;
  for (const ch of text) {
    const g = glyph(ch);
    for (let y = 0; y < GLYPH_H; y++) {
      const row = g[y];
      for (let x = 0; x < row.length; x++) if (row[x] === '#') plot(x0 + x, y);
    }
    x0 += g[0].length + 1;
  }
}

// Draws text into a 2D canvas context at integer scale.
export function drawText(ctx, text, x, y, scale, color) {
  ctx.fillStyle = color;
  rasterize(text, (px, py) => ctx.fillRect(x + px * scale, y + py * scale, scale, scale));
}
